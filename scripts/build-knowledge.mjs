import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const dataDirectory = new URL("../src/data/", import.meta.url);
const outputPath = fileURLToPath(new URL("knowledge.md", dataDirectory));
const sourceNames = [
  "profile",
  "timeline",
  "projects",
  "credentials",
  "faq",
  "glossary",
  "explainers",
];

async function readJson(name) {
  const path = new URL(`${name}.json`, dataDirectory);
  const content = await readFile(path, "utf8");
  try {
    return JSON.parse(content);
  } catch (error) {
    throw new Error(`Invalid JSON in src/data/${name}.json`, { cause: error });
  }
}

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function validateKnowledge(data) {
  for (const name of ["timeline", "projects", "credentials", "faq", "glossary", "explainers"]) {
    assert(Array.isArray(data[name]), `${name}.json must contain an array.`);
  }

  assert(data.faq.length >= 40, "faq.json must contain at least 40 entries.");
  assert(
    data.glossary.length >= 120,
    "glossary.json must contain at least 120 entries.",
  );
  assert(
    data.explainers.length >= 15,
    "explainers.json must contain at least 15 entries.",
  );

  const projectSlugs = new Set(data.projects.map((project) => project.slug));
  const glossaryIds = new Set(data.glossary.map((term) => term.id));
  const seenFaqIds = new Set();

  for (const item of data.glossary) {
    for (const termId of item.termesLies) {
      assert(
        glossaryIds.has(termId),
        `Unknown related glossary term "${termId}" in "${item.id}".`,
      );
    }
    for (const projectSlug of item.projetsLies) {
      assert(
        projectSlugs.has(projectSlug),
        `Unknown project "${projectSlug}" in glossary term "${item.id}".`,
      );
    }
    assert(
      typeof item.relu === "boolean",
      `Glossary term "${item.id}" must declare its review status.`,
    );
  }

  for (const item of data.faq) {
    assert(!seenFaqIds.has(item.id), `Duplicate FAQ id "${item.id}".`);
    seenFaqIds.add(item.id);
    for (const locale of ["fr", "en"]) {
      assert(
        item.question?.[locale] && item.answer?.[locale],
        `FAQ "${item.id}" is missing ${locale} content.`,
      );
    }
  }

  for (const item of data.explainers) {
    for (const field of ["term", "explanation", "analogy", "example"]) {
      for (const locale of ["fr", "en"]) {
        assert(
          item[field]?.[locale],
          `Explainer "${item.id}" is missing ${locale} ${field}.`,
        );
      }
    }
  }
}

function toSafeCredential(credential) {
  const {
    id,
    categorie,
    titre,
    organisme,
    date,
    lienVerification,
  } = credential;
  return { id, categorie, titre, organisme, date, lienVerification };
}

function toSection(title, value) {
  return `## ${title}\n\n\`\`\`json\n${JSON.stringify(value, null, 2)}\n\`\`\``;
}

async function main() {
  const data = Object.fromEntries(
    await Promise.all(
      sourceNames.map(async (name) => [name, await readJson(name)]),
    ),
  );

  validateKnowledge(data);

  const sections = [
    "# Base de connaissances du portfolio / Portfolio knowledge base",
    "Generated from the bilingual JSON source files. Do not edit this file directly.",
    toSection("Profil / Profile", data.profile),
    toSection("Parcours / Timeline", data.timeline),
    toSection("Projets / Projects", data.projects),
    toSection(
      "Diplômes et certificats / Degrees and certificates",
      data.credentials.map(toSafeCredential),
    ),
    toSection("FAQ", data.faq),
    toSection("Glossaire interne / Internal glossary", data.glossary),
    toSection("Explications / Explainers", data.explainers),
  ];

  await writeFile(outputPath, `${sections.join("\n\n")}\n`, "utf8");
  console.info(
    `Generated src/data/knowledge.md (${data.faq.length} FAQs, ${data.glossary.length} glossary terms, ${data.explainers.length} explainers).`,
  );
}

main().catch((error) => {
  console.error("Knowledge generation failed.", error);
  process.exitCode = 1;
});
